st.subheader("How SMARTFLOW Counts Objects")

st.markdown(
    """
    <div class="info-box">

    <b>1. Detection:</b>
    YOLO11 detects objects in every video frame.

    <br><br>

    <b>2. Tracking:</b>
    ByteTrack assigns a tracking ID to each detected object
    and attempts to maintain that ID across consecutive frames.

    <br><br>

    <b>3. Line Crossing:</b>
    SMARTFLOW calculates the center point of each tracked
    bounding box and checks whether it crosses the virtual
    counting line.

    <br><br>

    <b>4. Double-Count Prevention:</b>
    Once an object ID crosses the line, that ID is added to
    the counted-ID set. The same ID is not counted again.

    <br><br>

    <b>5. Object Classes:</b>
    The system is not restricted to vehicles. It can process
    persons, bicycles, cars, motorcycles, buses, trucks, and
    other classes supported by the YOLO model.

    </div>
    """,
    unsafe_allow_html=True,
)


