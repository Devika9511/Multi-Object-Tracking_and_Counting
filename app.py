def get_input_videos():
    """Find all MP4 input videos in the input folder."""
    if not os.path.isdir(INPUT_DIR):
        return []
    return sorted(
        [
            os.path.join(INPUT_DIR, name)
            for name in os.listdir(INPUT_DIR)
            if name.lower().endswith(".mp4")
        ]
    )

def video_stem(video_path):
    """Return the input video's filename without extension."""
    return os.path.splitext(os.path.basename(video_path))[0]

def video_output_path(video_path):
    """Return the H.264 output path preferred by the dashboard."""
    return os.path.join(
        OUTPUT_DIR,
        f"smartflow_{video_stem(video_path)}_tracked_h264.mp4",
    )

def video_raw_output_path(video_path):
    """Return the OpenCV output path."""
    return os.path.join(
        OUTPUT_DIR,
        f"smartflow_{video_stem(video_path)}_tracked.mp4",
    )

def video_data_path(video_path):
    """Return the per-video CSV generated by main.py."""
    return os.path.join(
        REPORT_DIR,
        f"{video_stem(video_path)}_traffic_data.csv",
    )


