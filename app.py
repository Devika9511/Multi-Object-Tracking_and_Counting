def find_video():
    """Return a sensible default input video."""
    videos = get_input_videos()
    if not videos:
        return None

    traffic = os.path.join(INPUT_DIR, "traffic.mp4")
    if traffic in videos:
        return traffic

    return videos[0]


def load_csv(data_file):
    """Load SMARTFLOW traffic data for the selected video."""
    if not os.path.exists(data_file):
        return None

    try:
        df = pd.read_csv(data_file)

        if df.empty:
            return None

        return df

    except Exception as exc:
        st.error(f"Could not read {data_file}: {exc}")
        return None


def number_value(row, column, default=0):
    """Safely read a numeric CSV value."""
    try:
        value = row.get(column, default)

        if pd.isna(value):
            return default

        return float(value)

    except Exception:
        return default


def integer_value(row, column, default=0):
    """Safely read an integer CSV value."""
    return int(round(number_value(row, column, default)))


def parse_object_types(value):
    """Parse the JSON object_types column."""
    if value is None or pd.isna(value):
        return {}

    try:
        data = json.loads(str(value))

        if isinstance(data, dict):
            return {
                str(key): int(float(val))
                for key, val in data.items()
            }

    except Exception:
        pass

    return {}


